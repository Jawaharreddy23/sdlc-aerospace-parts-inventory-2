"""Stage 3 agent - Build & Deploy.

Generates the SQL deployment package from the approved Jira story:
create_database.sql, create_schema.sql, create_tables.sql, create_views.sql,
procedures.sql, tasks.sql, validation_queries.sql and deployment_guide.md.
Generation is deterministic and idempotent so re-runs are safe.
"""
from __future__ import annotations

import re


def slug(name: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9]+", "_", str(name).strip().lower())
    return s.strip("_") or "project"


def _sql_str(value) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def generate_sql(project_slug: str, story: dict, analysis: dict) -> dict:
    """Return {filename: content} for the full deployment package."""
    db_name = "%s_db" % project_slug
    schema = "core"
    fqn = "%s.%s" % (db_name, schema)
    story_name = story.get("name", project_slug)
    tasks = story.get("tasks") or []
    acs = story.get("acceptance_criteria") or []

    banner = (
        "-- %s\n-- Generated by the SDLC Orchestration Platform for story %s\n"
        % ("=" * 74, story_name)
    )

    create_database = banner + (
        "-- create_database.sql - logical database for the project\n"
        "CREATE DATABASE IF NOT EXISTS %s;\n" % db_name
    )

    create_schema = banner + (
        "-- create_schema.sql - application schema\n"
        "CREATE SCHEMA IF NOT EXISTS %s;\n" % fqn
    )

    create_tables = banner + (
        "-- create_tables.sql - core tables\n"
        "CREATE TABLE IF NOT EXISTS %s.story_tasks (\n"
        "    task_id     INTEGER,\n"
        "    task_name   VARCHAR(500),\n"
        "    status      VARCHAR(20) DEFAULT 'TODO',\n"
        "    created_at  TIMESTAMP\n);\n\n"
        "CREATE TABLE IF NOT EXISTS %s.requirements_traceability (\n"
        "    trace_id               INTEGER,\n"
        "    requirement_text       VARCHAR(1000),\n"
        "    acceptance_criterion    VARCHAR(1000),\n"
        "    test_id                VARCHAR(20),\n"
        "    coverage_status        VARCHAR(20)\n);\n\n"
        "CREATE TABLE IF NOT EXISTS %s.test_results (\n"
        "    test_id      VARCHAR(20),\n"
        "    test_name    VARCHAR(300),\n"
        "    category     VARCHAR(50),\n"
        "    result       VARCHAR(10),\n"
        "    executed_at  TIMESTAMP\n);\n\n"
        "CREATE TABLE IF NOT EXISTS %s.deployment_audit (\n"
        "    audit_id    INTEGER,\n"
        "    stage       VARCHAR(50),\n"
        "    action      VARCHAR(100),\n"
        "    actor       VARCHAR(100),\n"
        "    logged_at   TIMESTAMP\n);\n"
        % (fqn, fqn, fqn, fqn)
    )

    create_views = banner + (
        "-- create_views.sql - reporting views\n"
        "CREATE OR REPLACE VIEW %s.v_story_summary AS\n"
        "SELECT\n"
        "    COUNT(*)                        AS total_tasks,\n"
        "    SUM(CASE WHEN status = 'DONE' THEN 1 ELSE 0 END) AS completed_tasks\n"
        "FROM %s.story_tasks;\n\n"
        "CREATE OR REPLACE VIEW %s.v_requirements_coverage AS\n"
        "SELECT\n"
        "    coverage_status,\n"
        "    COUNT(*) AS items\n"
        "FROM %s.requirements_traceability\n"
        "GROUP BY coverage_status;\n"
        % (fqn, fqn, fqn, fqn)
    )

    procedures = banner + (
        "-- procedures.sql - operational procedures\n"
        "CREATE OR REPLACE PROCEDURE %s.log_stage_approval(IN stage_name VARCHAR(50), IN actor_name VARCHAR(100))\n"
        "BEGIN\n"
        "    INSERT INTO %s.deployment_audit (audit_id, stage, action, actor, logged_at)\n"
        "    VALUES (UNIX_TIMESTAMP(), stage_name, 'approved', actor_name, CURRENT_TIMESTAMP());\n"
        "END;\n\n"
        "CREATE OR REPLACE PROCEDURE %s.update_task_status(IN task_id_in INTEGER, IN status_in VARCHAR(20))\n"
        "BEGIN\n"
        "    UPDATE %s.story_tasks SET status = status_in WHERE task_id = task_id_in;\n"
        "END;\n"
        % (fqn, fqn, fqn, fqn)
    )

    inserts = []
    for i, task in enumerate(tasks, 1):
        inserts.append(
            "INSERT INTO %s.story_tasks (task_id, task_name, status, created_at)\n"
            "VALUES (%d, %s, 'TODO', CURRENT_TIMESTAMP());"
            % (fqn, i, _sql_str(task[:500]))
        )
    tasks_sql = banner + "-- tasks.sql - story task seed data\n" + "\n".join(inserts) + "\n"

    validation_queries = banner + (
        "-- validation_queries.sql - post-deployment smoke checks\n"
        "-- 1. All story tasks were seeded.\n"
        "SELECT COUNT(*) AS seeded_tasks FROM %s.story_tasks;\n\n"
        "-- 2. No NULL task names.\n"
        "SELECT COUNT(*) AS null_task_names FROM %s.story_tasks WHERE task_name IS NULL;\n\n"
        "-- 3. Every requirement has a traceability row.\n"
        "SELECT COUNT(*) AS untraced FROM %s.requirements_traceability WHERE test_id IS NULL;\n\n"
        "-- 4. Test results summary.\n"
        "SELECT result, COUNT(*) AS tests FROM %s.test_results GROUP BY result;\n\n"
        "-- 5. Deployment audit entries exist.\n"
        "SELECT stage, action, logged_at FROM %s.deployment_audit ORDER BY logged_at;\n\n"
        "-- 6. Coverage distribution.\n"
        "SELECT * FROM %s.v_requirements_coverage;\n"
        % (fqn, fqn, fqn, fqn, fqn, fqn)
    )

    deployment_guide = (
        "# Deployment Guide - %s\n\n"
        "## Package contents\n"
        "| File | Purpose |\n"
        "| --- | --- |\n"
        "| create_database.sql | Creates the logical database |\n"
        "| create_schema.sql | Creates the application schema |\n"
        "| create_tables.sql | Creates core tables |\n"
        "| create_views.sql | Creates reporting views |\n"
        "| procedures.sql | Creates operational procedures |\n"
        "| tasks.sql | Seeds story task data |\n"
        "| validation_queries.sql | Post-deployment smoke checks |\n\n"
        "## Execution order\n"
        "1. Run `create_database.sql`\n"
        "2. Run `create_schema.sql`\n"
        "3. Run `create_tables.sql`\n"
        "4. Run `create_views.sql`\n"
        "5. Run `procedures.sql`\n"
        "6. Run `tasks.sql`\n"
        "7. Run `validation_queries.sql` and confirm all checks pass\n\n"
        "## Rollback plan\n"
        "The deployment is additive (CREATE IF NOT EXISTS / OR REPLACE), so rollback\n"
        "is safe: drop the schema `%s` and, if desired, the database `%s`.\n\n"
        "## Notes\n"
        "* Generated for story: %s\n"
        "* Acceptance criteria covered: %d\n"
        "* Tasks seeded: %d\n"
        % (story_name, fqn, db_name, story_name, len(acs), len(tasks))
    )

    return {
        "create_database.sql": create_database,
        "create_schema.sql": create_schema,
        "create_tables.sql": create_tables,
        "create_views.sql": create_views,
        "procedures.sql": procedures,
        "tasks.sql": tasks_sql,
        "validation_queries.sql": validation_queries,
        "deployment_guide.md": deployment_guide,
    }
